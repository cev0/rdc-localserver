function clone(value) {
  return value == null ? value : JSON.parse(JSON.stringify(value));
}

function worldCupRowAl(id) {
  const key = id == null ? "" : String(id).trim();
  const row = WORLD_CUP_ROWS.find(x => x.id === key);
  return row ? clone(row) : null;
}

function worldCupOptionIdsAl(id) {
  const row = worldCupRowAl(id);
  if (!row || typeof row.options !== "string") return [];
  return row.options.split("|").map(x => x.trim()).filter(Boolean);
}

function worldCupGoodsMaxAl(id) {
  const row = worldCupRowAl(id);
  if (!row || typeof row.goods_max !== "string") return [];
  return row.goods_max.split("|").map(token => {
    const [resourceId,amountRaw] = token.split(",");
    const amount = Number(amountRaw);
    return {
      resourceId:String(resourceId == null ? "" : resourceId).trim(),
      amount:Number.isFinite(amount) ? Math.trunc(amount) : 0
    };
  });
}

function worldCupRowsByNameTypeAl(nameType) {
  const key = String(nameType == null ? "" : nameType).trim();
  return WORLD_CUP_ROWS.filter(x => x.name_type === key).map(clone);
}

